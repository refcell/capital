#!/usr/bin/env python3
"""One-time migration: extract a dated call from every published report version.

Reads each version of research/<T>.md in git history (a rewritten report with a new
Date: is a separate call), extracts the header, price, scenario values and weights,
fair value, and Street target, and writes data/<T>/<date>/call.json and inputs.json.

Every extracted number carries a verbatim quote from the report version (or build
script) it came from, so `python3 -m capital.validate` can prove the extraction. A
field with no quotable source is left null. Hand-curated calls (any call.json without
"backfill_generated": true in notes) are never overwritten.

Writes data/BACKFILL.md listing what could not be extracted.

Usage: python3 scripts/backfill_calls.py [--ticker CNC]
"""

from __future__ import annotations

import argparse
import functools
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from capital import store  # noqa: E402
from capital.validate import normalize  # noqa: E402

GENERATED = "generated by scripts/backfill_calls.py"
MONTHS = "January|February|March|April|May|June|July|August|September|October|November|December"
NUM = r"\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?"


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def num(text: str) -> float:
    return float(text.replace(",", ""))


def parse_long_date(text: str) -> str | None:
    text = text.strip().replace("Sept.", "Sep.")
    for fmt in ("%B %d, %Y", "%b %d, %Y", "%b. %d, %Y", "%Y-%m-%d"):
        try:
            return datetime.strptime(text, fmt).date().isoformat()
        except ValueError:
            pass
    return None


# ---------------------------------------------------------------------------
# Report versions


@dataclass
class Version:
    path: str
    commit: str
    commit_date: str
    text: str


def report_versions() -> list[Version]:
    paths = sorted(set(git("log", "--format=", "--name-only", "--", "research/*.md").split()))
    out = []
    for path in paths:
        if path.endswith("TEMPLATE.md") or path.count("/") != 1:
            continue
        for line in git("log", "--format=%h %ad", "--date=short", "--", path).splitlines():
            commit, date = line.split()
            blob = store.git_blob(commit, path)
            if blob is None:  # deletion commit
                continue
            out.append(Version(path, commit, date, blob.decode("utf-8", errors="replace")))
    return out


# ---------------------------------------------------------------------------
# Header


def header_field(text: str, *names: str) -> tuple[str | None, str | None]:
    """Value and the full line for the first 'Name: value' header in the first 40 lines."""
    head = "\n".join(text.splitlines()[:40])
    for name in names:
        m = re.search(rf"^\**{name}\**\s*:\s*\**(.+?)\s*$", head, re.M | re.I)
        if m:
            return m.group(1).strip().rstrip("*").strip(), m.group(0)
    return None, None


def report_date(v: Version) -> tuple[str | None, str | None]:
    value, line = header_field(v.text, "Date")
    if value:
        iso = parse_long_date(value) or (value if re.fullmatch(r"\d{4}-\d{2}-\d{2}", value) else None)
        if iso:
            return iso, line
    head = "\n".join(v.text.splitlines()[:15])
    m = re.search(rf"(?:Last Updated:\s*|^#+\s*)((?:{MONTHS}) \d{{1,2}}, \d{{4}})", head, re.M)
    if m:
        return parse_long_date(m.group(1)), m.group(0)
    return None, None


def title(text: str) -> tuple[str | None, str | None, str | None]:
    """Company, exchange, ticker from '# Company (EXCHANGE: T) ...'."""
    m = re.search(r"^#\s+(.+?)\s*\(([A-Za-z ]+?)\s*:\s*([A-Za-z0-9.\-]+)\)", text, re.M)
    if not m:
        return None, None, None
    return m.group(1).strip(), m.group(2).strip(), m.group(3).strip().upper()


STATUS = [
    ("post_earnings", r"post[- ]?(earnings|q\d|fy|clinical)|post-.*update"),
    ("pre_earnings", r"pre[- ]?(earnings|q\d)"),
    ("refresh", r"refresh"),
    ("thesis_update", r"thesis update"),
    ("initial", r"initia"),
]


def norm_status(text: str | None) -> str | None:
    if not text:
        return None
    low = text.lower()
    for key, pat in STATUS:
        if re.search(pat, low):
            return key
    return "other"


def norm_stance(text: str) -> tuple[str, str]:
    low = text.lower()
    first = re.split(r"[—–\-/;,(:]| but ", low, maxsplit=1)[0].strip()
    if "bearish" in first or first.startswith("avoid") or first.startswith("sell"):
        stance = "avoid"
    elif re.match(r"(own|buy)\b", first):
        stance = "own"
    elif first.startswith("pass"):
        stance = "pass"
    elif first.startswith("needs more work"):
        stance = "needs_more_work"
    else:  # watch, hold, cautious watch
        stance = "watch"
    if re.search(r"bearish|negative|cautious|\bavoid", low):
        bias = "negative"
    elif re.search(r"positive|constructive|attractive|\bown\b|\bbuy\b", low):
        bias = "positive"
    else:
        bias = "neutral"
    return stance, bias


LENSES = [
    ("pb_roe", r"p/b|price[- ]to[- ]book|\broe\b|rotce|book value|residual income|p/tbv"),
    ("p_ffo", r"ffo"),
    ("nav", r"\bnav\b|pipeline npv|rnpv"),
    ("sotp", r"sotp|sum[- ]of[- ]the[- ]parts"),
    ("ev_ebitda", r"ev\s*/\s*(adjusted )?ebitda|ebitda ×|ebitda x|exit ev/ebitda"),
    ("ev_gross_profit", r"ev\s*/\s*gross profit"),
    ("ev_sales", r"ev\s*/\s*(forward )?(sales|revenue)|revenue multiple"),
    ("dcf", r"dcf|discounted"),
    ("fcf", r"fcf|free[- ]cash[- ]flow|owner earnings|cash flow"),
    ("pe", r"p/e|\bpe\b|earnings|eps"),
    ("dividend", r"dividend"),
]


def norm_lens(text: str | None) -> str | None:
    if not text:
        return None
    low = text.lower()
    hits = []
    for key, pat in LENSES:
        m = re.search(pat, low)
        if m:
            hits.append((m.start(), key))
    return min(hits)[1] if hits else "other"


