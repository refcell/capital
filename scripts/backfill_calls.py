# Assemble


def build_call(v: Version, models: dict[str, list[str]], scripts: list[str], gaps: list[str]) -> tuple[dict, dict] | None:
    date, date_line = report_date(v)
    company, exchange, ticker = title(v.text)
    tick_value, _ = header_field(v.text, "Ticker")
    if tick_value and ":" in tick_value:
        exchange = exchange or tick_value.split(":")[0].strip()
        ticker = ticker or tick_value.split(":")[1].split()[0].strip().upper()
    ticker = (ticker or Path(v.path).stem).upper()
    tag = f"{ticker} {v.commit}"
    if not date:
        gaps.append(f"{tag}: no report date found; skipped")
        return None
    company_hdr, _ = header_field(v.text, "Company")
    company = company_hdr or company or ticker

    stance_text, stance_line = header_field(v.text, "Current stance", "Stance", "Rating", "Recommendation")
    if not stance_text:
        m = re.search(r"\b(?:stance|rating|recommendation)\s*(?:is|:)\s*\**(Own|Watch|Pass|Avoid|Hold|Buy|Sell)\b", v.text, re.I)
        if m:
            stance_text, stance_line = m.group(1), m.group(0)
    if not stance_text:
        gaps.append(f"{tag}: no stance stated")
    stance, bias = norm_stance(stance_text) if stance_text else (None, None)

    lens_text, _ = header_field(v.text, "Primary valuation lens")
    status_text, _ = header_field(v.text, "Research status")
    sector, _ = header_field(v.text, "Sector / industry", "Sector")

    p = price(v.text)
    if not p:
        gaps.append(f"{tag}: no 'closed at $X on DATE' price; skipped")
        return None
    px, px_date, px_quote = p

    evidence: dict[str, str] = {"price.value": px_quote}
    if stance_line:
        evidence["stance_text"] = stance_line
    notes = [GENERATED]

    scen = scenarios(v.text)
    scen_values: dict[str, Any] = {}
    if scen:
        scen_values = scen.values
        evidence.update(scen.evidence)
    else:
        gaps.append(f"{tag}: no bear/base/bull value table parsed")

    fv = None
    stated_all = stated_fair_values(v.text)
    stated = stated_all[0] if stated_all else None
    if len({x for x, _ in stated_all}) > 1:
        notes.append("The report states more than one probability-weighted value: " + ", ".join(sorted({f"${x:g}" for x, _ in stated_all})) + "; the first is used.")
    weighted = store.weighted_value(scen_values) if scen_values else None
    if stated:
        fv = {"value": stated[0], "method": "stated"}
        evidence["fair_value.value"] = stated[1]
        if weighted is not None and abs(weighted - stated[0]) > 0.015 * stated[0]:
            notes.append(f"Stated fair value ${stated[0]:g} differs from the weighted scenario value ${weighted:.2f}.")
    elif weighted is not None:
        fv = {"value": round(weighted, 2), "method": "weighted"}
    elif scen_values.get("base"):
        fv = {"value": scen_values["base"]["value"], "method": "base"}

    street = None
    sm = street_mean(v.text)
    if sm:
        street = {"target_mean": sm[0]}
        evidence["street.target_mean"] = sm[1]
    dev = None
    fair = fv["value"] if fv else None
    if fair and street:
        dev = {"pct": round((fair / street["target_mean"] - 1) * 100, 1), "reason": None}

    model = model_for(company, ticker, date, models)
    script = script_for(ticker, model, scripts)
    artifacts: dict[str, Any] = {"report": {"path": v.path, "commit": v.commit}}
    proj_paths = [f"projections/{ticker}.md"]
    proj = companion(list(dict.fromkeys(proj_paths)), date, v.commit_date)
    if proj:
        artifacts["projection"] = proj
    if model:
        artifacts["model"] = companion([model], date, v.commit_date) or {"path": model, "commit": None}
        if artifacts["model"]["commit"] is None:
            del artifacts["model"]
    if script:
        bs = companion([script], date, v.commit_date)
        if bs:
            artifacts["build_script"] = bs

    if px_date is None:
        notes.append("The report does not state the close date of its reference price.")
    call = {
        "schema_version": 1,
        "ticker": ticker,
        "exchange": exchange,
        "company": company,
        "sector": sector,
        "date": date,
        "origin": "backfill",
        "research_status": norm_status(status_text),
        "research_status_text": status_text,
        "stance": stance,
        "bias": bias,
        "stance_text": stance_text or "unstated",
        "primary_lens": norm_lens(lens_text),
        "lens_text": lens_text,
        "price": {"value": px, "currency": "USD", "date": px_date},
        "scenarios": scen_values,
        "fair_value": fv,
        "horizon_years": None,
        "street": street,
        "deviation_from_street": dev,
        "catalysts": [],
        "next_review": None,
        "change_my_mind": [],
        "artifacts": artifacts,
        "evidence": evidence,
        "notes": notes,
    }

    values: dict[str, Any] = {
        "price": {"value": px, "as_of": px_date, "source": f"{v.path}@{v.commit}", "quote": px_quote},
    }
    for key, (value, quote) in snapshot_values(v.text).items():
        values[key] = {"value": value, "as_of": px_date, "source": f"{v.path}@{v.commit}", "quote": quote}
    if street:
        values["street_target_mean"] = {"value": street["target_mean"], "as_of": None, "source": f"{v.path}@{v.commit}", "quote": evidence["street.target_mean"]}
    bs = artifacts.get("build_script")
    if bs:
        blob = store.git_blob(bs["commit"], bs["path"])
        m = BETA_RE.search(blob.decode("utf-8", errors="replace")) if blob else None
        if m and 0 < float(m.group(1)) < 5:
            values["beta"] = {"value": float(m.group(1)), "as_of": None, "source": f"{bs['path']}@{bs['commit']}", "quote": m.group(0).strip()}
    inputs = {
        "schema_version": 1,
        "ticker": ticker,
        "date": date,
        "currency": "USD",
        "origin": "backfill",
        "values": values,
        "notes": [GENERATED],
    }
    return call, inputs


def is_generated(path: Path) -> bool:
    if not path.exists():
        return True
    return GENERATED in store.load_json(path).get("notes", [])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ticker")
    args = parser.parse_args(argv)

    models = models_by_date()
    scripts = build_scripts()
    gaps: list[str] = []
    written: dict[str, Version] = {}
    versions = report_versions()
    if args.ticker:
        versions = [v for v in versions if Path(v.path).stem.upper() == args.ticker.upper()]
    # Oldest first, so the newest commit of a given call date wins.
    order = {h: i for i, h in enumerate(reversed(git("log", "--format=%h").split()))}
    versions.sort(key=lambda v: order[v.commit])
    # A rename or a no-op commit repeats a version; keep the earliest commit of identical content.
    seen_text: set[tuple[str, str]] = set()
    unique = []
    for v in versions:
        key = (Path(v.path).stem.upper(), v.text)
        if key not in seen_text:
            seen_text.add(key)
            unique.append(v)
    versions = unique
    results: dict[str, tuple[dict, dict, Version]] = {}
    for v in versions:
        built = build_call(v, models, scripts, gaps)
        if not built:
            continue
        call, inputs = built
        results[f"{call['ticker']}/{call['date']}"] = (call, inputs, v)

    kept = 0
    for key, (call, inputs, v) in sorted(results.items()):
        d = store.call_dir(call["ticker"], call["date"])
        if not is_generated(d / "call.json"):
            kept += 1
            continue
        store.write_json(d / "call.json", call)
        store.write_json(d / "inputs.json", inputs)
        written[key] = v

    gap_keys = defaultdict(list)
    written_tags = {f"{c['ticker']} {v.commit}" for c, _, v in results.values()}
    for g in gaps:
        tag = g.split(":")[0]
        if tag in written_tags or "skipped" in g:
            gap_keys[tag].append(g.split(": ", 1)[1])
    lines = [
        "# Backfill report",
        "",
        f"`scripts/backfill_calls.py` read {len(versions)} report versions and wrote {len(written)} calls "
        "(when several commits share a report date, the latest wins); "
        f"{kept} hand-curated call(s) were left untouched. Every extracted number has a verbatim evidence quote "
        "checked by `python3 -m capital.validate`. Fields the extractor could not quote are null.",
        "",
        "## Gaps",
        "",
    ]
    for k in sorted(gap_keys):
        lines.append(f"- {k}: {'; '.join(gap_keys[k])}")
    if not gap_keys:
        lines.append("None.")
    if not args.ticker:
        (store.DATA / "BACKFILL.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(written)} calls, kept {kept}, {len(gaps)} gap(s)")
    for g in gaps:
        print("  " + g)
    return 0


if __name__ == "__main__":
    sys.exit(main())
