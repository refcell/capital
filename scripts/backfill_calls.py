# Fair value and Street


FV_RE = re.compile(
    rf"probability[- ]weighted (?:fair value|FV|value|model|target|price target|intrinsic value|average)"
    rf"(?: estimate| per share| target)?(?: from [a-z ]+)?(?: (?:of|is|was|at|produces|comes to|=|:|lands at|works out to))?"
    rf"(?: approximately| roughly| about| ~)?\s*:?\s*\**\s*~?(?:US)?\$({NUM})",
    re.I,
)


def stated_fair_values(text: str) -> list[tuple[float, str]]:
    """Every point estimate stated as a probability-weighted value; ranges are skipped."""
    flat = normalize(text)
    out = []
    for m in FV_RE.finditer(flat):
        if re.match(rf"\s*(?:-|–|to)\s*\$?{NUM}", flat[m.end():]):
            continue
        out.append((num(m.group(1)), m.group(0)))
    return out


STREET_RES = [
    re.compile(rf"(?:analysts?|analyst consensus|consensus|Street)\s+(?:average|mean)(?: price)? target(?: price)?(?: (?:of|is|was|at))?\s*(?:US)?\$({NUM})", re.I),
    re.compile(rf"(?:average|mean) (?:analyst |Street |consensus |1-year |12-month )?(?:price )?target(?: price)?(?: (?:of|is|was|at|sits at|stands at))?\s*(?:US)?\$({NUM})", re.I),
    re.compile(rf"average an? \$({NUM}) (?:price )?target", re.I),
    re.compile(rf"(?:Street|analyst|consensus) PT\s*\|?\s*\$({NUM}) avg", re.I),
]


def street_mean(text: str) -> tuple[float, str] | None:
    flat = normalize(text)
    for rx in STREET_RES:
        m = rx.search(flat)
        if m:
            return num(m.group(1)), m.group(0)
    return None


