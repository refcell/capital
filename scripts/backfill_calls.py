# Scenario tables


CASES = ("bear", "base", "bull")


def tables(text: str) -> list[list[tuple[str, list[str]]]]:
    """Markdown tables as lists of (raw line, cells), separator rows dropped."""
    out, cur = [], []
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("|") and s.count("|") >= 3:
            if re.fullmatch(r"\|[\s:\-|]+\|?", s):
                continue
            cells = [c.strip() for c in s.strip("|").split("|")]
            cur.append((line, cells))
        elif cur:
            out.append(cur)
            cur = []
    if cur:
        out.append(cur)
    return out


def case_of(label: str) -> str | None:
    low = normalize(label).lower()
    for case in CASES:
        if re.match(rf"{case}\b", low):
            return case
    return None


VALUE_HEADER = re.compile(
    r"target|fair value|value\s*/\s*share|value per share|implied (?:price|value|share)|per[- ]share value|"
    r"present value|price target|implied equity value/share|^value$|equity value per share|intrinsic",
    re.I,
)
BAD_VALUE_HEADER = re.compile(r"weighted|upside|downside|return|irr|multiple|probability|weight|cagr|vs", re.I)
WEIGHT_HEADER = re.compile(r"^(?:weight|probability|prob\.?)$|probability|weight", re.I)
BAD_WEIGHT_HEADER = re.compile(r"weighted", re.I)


def money_cell(cell: str) -> tuple[float, float | None, float | None] | None:
    """(value, low, high) from '$46.20', 'About $51', '$8-$12', '**$53.30**'. None when unclear."""
    c = normalize(cell).replace("−", "-").replace("–", "-").replace("—", "-")
    c = re.sub(r"(?i)^(about|approx\.?|approximately|~|roughly|c\.)\s*", "", c)
    m = re.fullmatch(rf"(?:US)?\$\s*({NUM})\s*(?:-|to)\s*(?:US)?\$?\s*({NUM})(?:\s*/\s*share)?", c)
    if m:
        lo, hi = num(m.group(1)), num(m.group(2))
        if lo < hi:
            return round((lo + hi) / 2, 4), lo, hi
        return None
    m = re.fullmatch(rf"~?(?:US)?\$\s*({NUM})(?:\s*/\s*share|\s*per share)?(?:\s*\(.*\))?", c)
    if m:
        return num(m.group(1)), None, None
    return None


def pct_cell(cell: str) -> float | None:
    c = normalize(cell)
    m = re.fullmatch(r"~?(\d{1,3}(?:\.\d+)?)\s*%", c)
    if m:
        return num(m.group(1)) / 100
    m = re.fullmatch(r"0?\.(\d+)", c)
    if m:
        return float("0." + m.group(1))
    return None


@dataclass
class Scenarios:
    values: dict[str, dict[str, Any]] = field(default_factory=dict)
    evidence: dict[str, str] = field(default_factory=dict)
    score: int = 0


def row_oriented(table: list[tuple[str, list[str]]]) -> Scenarios | None:
    header_idx = None
    for i, (_, cells) in enumerate(table):
        if any(VALUE_HEADER.search(c) and not BAD_VALUE_HEADER.search(c) for c in cells[1:]):
            header_idx = i
            break
    if header_idx is None:
        return None
    header = table[header_idx][1]
    vcols = [j for j, c in enumerate(header) if j > 0 and VALUE_HEADER.search(c) and not BAD_VALUE_HEADER.search(c)]
    wcols = [j for j, c in enumerate(header) if j > 0 and WEIGHT_HEADER.search(c) and not BAD_WEIGHT_HEADER.search(c)]
    out = Scenarios()
    for line, cells in table[header_idx + 1 :]:
        case = case_of(cells[0]) if cells else None
        if not case or case in out.values:
            continue
        parsed = None
        for j in vcols:
            if j < len(cells):
                parsed = money_cell(cells[j])
                if parsed:
                    break
        if not parsed:
            continue
        value, lo, hi = parsed
        entry: dict[str, Any] = {"value": value}
        if lo is not None:
            entry["low"], entry["high"] = lo, hi
        weight = None
        for j in wcols:
            if j < len(cells):
                weight = pct_cell(cells[j])
                if weight is not None:
                    break
        if weight is None:
            m = re.search(r"\((\d{1,3})%\)", cells[0])
            if m:
                weight = int(m.group(1)) / 100
        if weight is not None:
            entry["weight"] = weight
        out.values[case] = entry
        out.evidence[f"scenarios.{case}.value"] = line.strip()
    return out if out.values else None


VALUE_ROW = re.compile(
    r"^(?:present (?:fair )?value\s*(?:/|per)\s*share|target(?: price)?|price target|fair value|value\s*/\s*share|value per share|implied (?:price|value|share price)|"
    r"implied value per share|per[- ]share value|intrinsic value|equity value per share|scenario value|"
    r"implied price|target value|5y target|.*target price)",
    re.I,
)
WEIGHT_ROW = re.compile(r"^(?:weight|probability|prob\.?|scenario weight)\b", re.I)


def column_oriented(table: list[tuple[str, list[str]]]) -> Scenarios | None:
    header = table[0][1]
    cols = {case: j for j, c in enumerate(header) for case in [case_of(c)] if case}
    if len(cols) < 2:
        return None
    out = Scenarios()
    for line, cells in table[1:]:
        label = normalize(cells[0]) if cells else ""
        if VALUE_ROW.match(label) and not re.search(r"weighted|upside|return", label, re.I) and "scenarios.bear.value" not in out.evidence:
            parsed = {case: money_cell(cells[j]) for case, j in cols.items() if j < len(cells)}
            if all(parsed.values()):
                for case, (value, lo, hi) in parsed.items():
                    entry = out.values.setdefault(case, {})
                    entry["value"] = value
                    if lo is not None:
                        entry["low"], entry["high"] = lo, hi
                    out.evidence[f"scenarios.{case}.value"] = line.strip()
        elif WEIGHT_ROW.match(label):
            weights = {case: pct_cell(cells[j]) for case, j in cols.items() if j < len(cells)}
            if all(w is not None for w in weights.values()):
                for case, w in weights.items():
                    out.values.setdefault(case, {})["weight"] = w
                    out.evidence[f"scenarios.{case}.weight"] = line.strip()
    out.values = {k: v for k, v in out.values.items() if "value" in v}
    return out if out.values else None


def scenarios(text: str) -> Scenarios | None:
    best = None
    for t in tables(text):
        for cand in (row_oriented(t), column_oriented(t)):
            if not cand:
                continue
            vals = cand.values
            if any(c not in vals for c in CASES):
                continue
            ordered = vals["bear"]["value"] <= vals["base"]["value"] <= vals["bull"]["value"]
            weights = [vals[c].get("weight") for c in CASES]
            has_weights = all(w is not None for w in weights) and abs(sum(weights) - 1) <= 0.011  # type: ignore[arg-type]
            cand.score = (2 if ordered else 0) + (1 if has_weights else 0)
            if not has_weights:
                for c in CASES:
                    vals[c].pop("weight", None)
                    cand.evidence.pop(f"scenarios.{c}.weight", None)
            if not ordered:
                continue
            if best is None or cand.score > best.score:
                best = cand
    return best


