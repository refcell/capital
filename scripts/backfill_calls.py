@functools.lru_cache(maxsize=None)
def file_history(path: str) -> tuple[tuple[str, str, str], ...]:
    """(commit, date, path at that commit), newest first, following renames."""
    out = []
    log = git("log", "--format=@%h %ad", "--date=short", "--name-only", "--follow", "--", path)
    commit = date = None
    for line in log.splitlines():
        if line.startswith("@"):
            commit, date = line[1:].split()
        elif line.strip() and commit:
            out.append((commit, date, line.strip()))
            commit = None
    return tuple(out)


def companion(paths: list[str], call_date: str, commit_date: str) -> dict[str, str] | None:
    """The version of the first existing path whose commit is closest to the report commit."""
    best = None
    for path in paths:
        for commit, date, old_path in file_history(path):
            blob = store.git_blob(commit, old_path)
            if blob is None:
                continue
            gap = abs((datetime.fromisoformat(date) - datetime.fromisoformat(commit_date)).days)
            if gap <= 4 and (best is None or gap < best[0]):
                best = (gap, {"path": old_path, "commit": commit})
    return best[1] if best else None


def all_repo_paths() -> list[str]:
    return git("log", "--format=", "--name-only", "--all").split("\n")


def models_by_date() -> dict[str, list[str]]:
    paths = set(p for p in all_repo_paths() if p.endswith(".xlsx") and p.startswith("models/"))
    by: dict[str, list[str]] = defaultdict(list)
    for p in paths:
        m = re.search(r"(\d{4}-\d{2}-\d{2})", p)
        if m:
            by[m.group(1)].append(p)
    return by


def build_scripts() -> list[str]:
    return sorted(set(p for p in all_repo_paths() if re.search(r"(^|/)_?build_.*\.py$", p)))


def model_for(company: str, ticker: str, date: str, models: dict[str, list[str]]) -> str | None:
    words = [w for w in re.findall(r"[A-Za-z0-9&']+", company) if len(w) > 2 and w.lower() not in {"inc", "corp", "the", "group", "holdings", "ltd", "plc", "company", "corporation"}]
    d0 = datetime.fromisoformat(date)
    for delta in range(0, 5):
        for sign in (1, -1):
            d = (d0 + sign * timedelta(days=delta)).date().isoformat()
            for p in models.get(d, []):
                name = Path(p).name
                if re.search(rf"\b{re.escape(ticker)}\b", name) or (words and words[0].lower() in name.lower()):
                    return p
    return None


@functools.lru_cache(maxsize=None)
def script_text(path: str) -> bytes:
    hist = file_history(path)
    return (store.git_blob(hist[0][0], hist[0][2]) or b"") if hist else b""


def script_for(ticker: str, model_path: str | None, scripts: list[str]) -> str | None:
    if model_path:
        name = Path(model_path).name.encode()
        for s in scripts:
            if name in script_text(s):
                return s
    for s in scripts:
        stem = Path(s).stem.lower()
        if stem in (f"_build_{ticker.lower()}", f"_build_{ticker.lower()}_tab", f"build_{ticker.lower()}_model"):
            return s
    return None


BETA_RE = re.compile(r"^(?:BETA|beta)\s*=\s*([0-9.]+)\b.*$", re.M)


