# Price and snapshot


DATE_PAT = rf"(?:{MONTHS}) \d{{1,2}},? \d{{4}}|\d{{4}}-\d{{2}}-\d{{2}}"
PRICE_RES = [
    re.compile(rf"closed at (?:US)?\$({NUM}) on ({DATE_PAT})"),
    re.compile(rf"traded at (?:US)?\$({NUM}) on ({DATE_PAT})"),
    re.compile(rf"last printed (?:US)?\$({NUM})[^.]{{0,80}}? on ({DATE_PAT})"),
    re.compile(rf"Price:\s*(?:US)?\$({NUM}) at the ({DATE_PAT}) close"),
    re.compile(rf"(?:US)?\$({NUM}) close on ({DATE_PAT})"),
    re.compile(rf"(?:US)?\$({NUM}) as of the ({DATE_PAT}) close"),
    re.compile(rf"traded around (?:US)?\$({NUM}) intraday on ({DATE_PAT})"),
]
PRICE_RE = PRICE_RES[0]
FALLBACK_PRICE_RES = [
    re.compile(rf"(?:showed|at|was) \$({NUM})(?!\s*[-–])"),
]
CURRENT_PRICE_RE = re.compile(rf"Current Price\**:\**\s*~?\$({NUM})")


def price(text: str) -> tuple[float, str | None, str] | None:
    """(price, close date, quote). Close date is None when the report does not state one."""
    for rx in PRICE_RES:
        m = rx.search(text)
        if m:
            raw_date = re.sub(r"(\d) (\d{4})$", r"\1, \2", m.group(2).replace(",", ""))
            return num(m.group(1)), parse_long_date(raw_date), m.group(0)
    para = snapshot_paragraph(text) or "\n".join(text.splitlines()[:20])
    for rx in FALLBACK_PRICE_RES:
        m = rx.search(para)
        if m:
            return num(m.group(1)), None, m.group(0)
    m = CURRENT_PRICE_RE.search(text)
    if m:
        return num(m.group(1)), None, m.group(0)
    return None


def snapshot_paragraph(text: str) -> str:
    m = re.search(r"^\**(?:Price snapshot|Current Price)\**:.*$", text, re.M | re.I)
    if m:
        return m.group(0)
    m = next((m for rx in PRICE_RES for m in [rx.search(text)] if m), None)
    if not m:
        return ""
    start = text.rfind("\n\n", 0, m.start())
    end = text.find("\n\n", m.end())
    return text[start + 2 if start >= 0 else 0 : end if end >= 0 else len(text)]


def scaled(value: str, unit: str) -> float:
    unit = unit.lower()
    factor = {"trillion": 1e6, "billion": 1e3, "b": 1e3, "million": 1.0, "m": 1.0}[unit]
    return num(value) * factor


SNAPSHOT_PATTERNS = {
    "shares_outstanding_m": rf"(?:Using|With|At)\s+(?:approximately |roughly |about )?(?P<v>{NUM})\s*(?P<u>billion|million)\b[^.]*?shares",
    "market_cap_m": rf"market capitalization (?:was|is|of) (?:approximately |roughly |about )?(?:US)?\$(?P<v>{NUM})\s*(?P<u>trillion|billion|million)",
    "enterprise_value_m": rf"enterprise value (?:was|is|of) (?:approximately |roughly |about )?(?:US)?\$(?P<v>{NUM})\s*(?P<u>trillion|billion|million)",
}


def snapshot_values(text: str) -> dict[str, tuple[float, str]]:
    para = snapshot_paragraph(text)
    out = {}
    for key, pat in SNAPSHOT_PATTERNS.items():
        m = re.search(pat, para, re.I)
        if m:
            out[key] = (round(scaled(m.group("v"), m.group("u")), 3), m.group(0))
    return out


