def index_page(latest: dict[str, store.Call], all_calls: list[store.Call]) -> str:
    out = [HEADER, "# Coverage library\n"]
    out.append(
        f"{len(latest)} companies, {len(all_calls)} dated calls. Every number comes from `data/`, which is "
        "captured once per research run and never re-fetched. Prices are marked through "
        f"{score.last_date() or '—'}.\n"
    )
    out.append(
        "Pages: [Scorecard](SCORECARD.md) · [Calendar](CALENDAR.md) · [Base rates](BASE_RATES.md) · "
        "[Multiples](MULTIPLES.md)\n"
    )
    out.append("## Rating scale\n")
    out.append(
        f"The rule rating is derived from each call's fair value versus its price, annualized over "
        f"{config.RATING_HORIZON_YEARS} years; the benchmark is {config.RATING_BENCHMARK} total return over the same horizon. "
        "The published stance can differ; the scorecard tracks both. Thresholds live in `capital/config.py`.\n"
    )
    out.append("| Rating | Definition | Latest calls (rule) | Latest calls (published stance) |\n|---|---|---:|---:|")
    rule_counts = Counter(score.rule_rating(c.call) for c in latest.values())
    stance_counts = Counter(c.call.get("stance") for c in latest.values())
    for r, text in config.RATING_DEFINITIONS.items():
        out.append(f"| {r.capitalize()} | {text} | {rule_counts.get(r, 0)} | {stance_counts.get(r, 0)} |")
    other = sum(v for k, v in stance_counts.items() if k not in config.RATING_DEFINITIONS)
    out.append(f"| Other | Pass, needs more work, unstated, or no fair value | {rule_counts.get(None, 0)} | {other} |")
    out.append("")
    out.append("## Companies\n")
    out.append(
        "Status comes from `data/coverage.csv`: active names get an update after every earnings release, watchlist "
        "names wait for their entry price, dropped names get no more updates.\n"
    )
    cov = store.coverage()
    out.append("| Ticker | Company | Sector | Status | Latest | Calls | Stance | Rule | Price | Fair value | Exp. return / yr | Since call | vs SPY |")
    out.append("|---|---|---|---|---|---:|---|---|---:|---:|---:|---:|---:|")
    counts = Counter(c.ticker for c in all_calls)
    for t in sorted(latest):
        d = latest[t].call
        mk = score.mark(d)
        sector = (d.get("sector") or "—").split("/")[0].strip()
        out.append(
            f"| [{t}]({t}.md) | {d['company']} | {sector} | {cov.get(t, {}).get('status', '—')} | {d['date']} | {counts[t]} | {stance_label(d)} | "
            f"{(score.rule_rating(d) or '—').capitalize()} | {money(d['price']['value'])} | {money(store.fair_value(d))} | "
            f"{pct(score.expected_annual(d))} | {pct(mk.ret) if mk else '—'} | {pct(mk.excess) if mk else '—'} |"
        )
    out.append("")
    return "\n".join(out)


