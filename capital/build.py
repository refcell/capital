def outputs() -> dict[Path, str]:
    all_calls = sorted(store.iter_calls(), key=lambda c: (c.ticker, c.date))
    by_ticker: dict[str, list[store.Call]] = defaultdict(list)
    for c in all_calls:
        by_ticker[c.ticker].append(c)
    latest = store.latest_calls()
    files = {
        store.DATA / "calls.csv": calls_csv(all_calls),
        LIBRARY / "README.md": index_page(latest, all_calls),
        LIBRARY / "SCORECARD.md": scorecard(all_calls),
    }
    for t, calls in by_ticker.items():
        files[LIBRARY / f"{t}.md"] = company_page(t, calls)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if any generated file is out of date")
    args = parser.parse_args(argv)
    files = outputs()
    stale = []
    for path, text in files.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    known = set(files)
    orphans = [p for p in LIBRARY.glob("*.md") if p not in known] if LIBRARY.exists() else []
    if args.check:
        for p in stale + orphans:
            print(f"out of date: {p.relative_to(store.ROOT)}")
        if stale or orphans:
            print("run: python3 -m capital.build", file=sys.stderr)
            return 1
        print(f"ok: {len(files)} generated files up to date")
        return 0
    for p in orphans:
        p.unlink()
    print(f"wrote {len(stale)} of {len(files)} generated files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
