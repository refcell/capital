def mean(xs: list[float]) -> float | None:
    return sum(xs) / len(xs) if xs else None


def claims_section(all_calls: list[store.Call]) -> list[str]:
    """Brier scores and calibration for resolved probability claims."""
    claims = {f"{c.key}#{k['id']}": (c, k) for c in all_calls for k in c.call.get("claims") or []}
    outcomes = {r["claim"]: r for c in all_calls for r in c.call.get("resolutions") or []}
    out = ["## Probability claims\n"]
    if not claims:
        out.append(
            "No call has made resolvable probability claims yet. Every new research run must make at least three "
            "(see `capital/validate.py`); later calls record outcomes in `resolutions`, and this section then shows "
            "Brier scores and a calibration table.\n"
        )
        return out
    resolved = [(claims[k][1]["probability"], outcomes[k]["outcome"]) for k in claims if k in outcomes]
    asof = score.last_date() or ""
    overdue = [k for k, (c, cl) in claims.items() if k not in outcomes and cl["resolve_by"] < asof]
    out.append(f"{len(claims)} claims made, {len(resolved)} resolved, {len(overdue)} past their resolve-by date without a resolution.\n")
    if resolved:
        brier = sum((p - (1.0 if o else 0.0)) ** 2 for p, o in resolved) / len(resolved)
        out.append(f"Brier score: {brier:.3f} (0 is perfect; always saying 50% scores 0.250).\n")
        out.append("| Stated probability | Claims | Came true |\n|---|---:|---:|")
        for lo, hi in ((0, 0.2), (0.2, 0.4), (0.4, 0.6), (0.6, 0.8), (0.8, 1.01)):
            b = [o for p, o in resolved if lo <= p < hi]
            if b:
                out.append(f"| {lo:.0%}–{min(hi, 1):.0%} | {len(b)} | {sum(b) / len(b):.0%} |")
        out.append("")
    if overdue:
        out.append("Overdue: " + ", ".join(sorted(overdue)) + "\n")
    return out


def scorecard(all_calls: list[store.Call]) -> str:
    asof = score.last_date()
    marked = [(c, score.mark(c.call)) for c in all_calls]
    marked = [(c, m) for c, m in marked if m]
    out = [HEADER, "# Scorecard\n"]
    out.append(
        f"Every dated call marked against committed prices through {asof}. Returns use the adjusted close, so "
        f"dividends, splits, and spin-offs do not move them; \"vs SPY\" is the excess over {config.RATING_BENCHMARK} "
        "from the same start date. Most calls are months old against a "
        f"{config.RATING_HORIZON_YEARS}-year rating horizon, so these are interim marks, not verdicts.\n"
    )
    out.append(f"{len(marked)} of {len(all_calls)} calls have a mark.\n")

    def group_table(title: str, key) -> None:
        groups: dict[str, list] = defaultdict(list)
        for c, m in marked:
            groups[key(c)].append(m)
        out.append(f"## {title}\n")
        out.append("| Group | Calls | Median age (days) | Mean return | Mean vs SPY | Beat SPY |\n|---|---:|---:|---:|---:|---:|")
        for g in sorted(groups, key=lambda x: (x == "—", x)):
            ms = groups[g]
            ex = [m.excess for m in ms if m.excess is not None]
            ages = [(score.years_between(m.start, m.as_of) * 365.25) for m in ms]
            beat = sum(1 for e in ex if e > 0)
            out.append(
                f"| {g} | {len(ms)} | {median(ages):.0f} | {pct(mean([m.ret for m in ms]))} | {pct(mean(ex))} | "
                f"{beat}/{len(ex)} |"
            )
        out.append("")

    group_table("By published stance", lambda c: stance_label(c.call))
    group_table("By rule rating", lambda c: (score.rule_rating(c.call) or "—").capitalize())

    def upside_bucket(c: store.Call) -> str:
        fv = store.fair_value(c.call)
        if fv is None:
            return "—"
        up = fv / c.call["price"]["value"] - 1
        for lo, label in ((0.7, "70%+"), (0.3, "30% to 70%"), (0.1, "10% to 30%"), (-0.1, "-10% to 10%")):
            if up >= lo:
                return label
        return "below -10%"

    group_table("By stated upside to fair value", upside_bucket)
    out.append(
        "Calibration context: published 12-month price targets are met at the horizon only about 38% of the time "
        "(Bradshaw, Brown and Huang 2013), and targets 70% or more away from the price are hit under 25% of the time "
        "(Asquith, Mikhail and Au 2005). Large stated upside is a calibration risk until the scorecard shows otherwise.\n"
    )

    out.extend(claims_section(all_calls))

    bands = Counter(m.band for _, m in marked if m.band)
    total = sum(bands.values())
    out.append("## Where marks sit in the scenario range\n")
    out.append(
        "A calibrated set of calls should see marks spread across the bands roughly in line with the scenario "
        "weights once horizons pass. Early on, most marks should sit near the starting price.\n"
    )
    out.append("| Band | Calls | Share |\n|---|---:|---:|")
    for b in score.BANDS:
        out.append(f"| {b} | {bands.get(b, 0)} | {pct(bands.get(b, 0) / total if total else None, signed=False)} |")
    out.append("")

    out.append("## Every call\n")
    out.append("| Call | Stance | Rule | Price | Fair value | Mark | Since call | vs SPY | Band |\n|---|---|---|---:|---:|---:|---:|---:|---|")
    for c, m in sorted(marked, key=lambda x: (x[1].excess is None, -(x[1].excess or 0))):
        d = c.call
        out.append(
            f"| [{c.key}]({c.ticker}.md) | {stance_label(d)} | {(score.rule_rating(d) or '—').capitalize()} | {money(d['price']['value'])} | "
            f"{money(store.fair_value(d))} | {money(m.mark)} | {pct(m.ret)} | {pct(m.excess)} | {m.band or '—'} |"
        )
    out.append("")
    return "\n".join(out)


