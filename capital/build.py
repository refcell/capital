"""Regenerate every derived file from the data store. Run: python3 -m capital.build

Outputs (all generated; do not edit by hand):
    data/calls.csv            one row per call: the ratings and price-target history
    library/README.md         the coverage index with the rating distribution
    library/<TICKER>.md       one page per company: current view and every dated call
    library/SCORECARD.md      how past calls have done against committed prices

`--check` exits 1 when a generated file is out of date (CI runs this).
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
from collections import Counter, defaultdict
from pathlib import Path
from statistics import median
from typing import Any
from urllib.parse import quote

from capital import config, score, store

LIBRARY = store.ROOT / "library"
REPO_URL = "https://github.com/refcell/capital"
HEADER = "<!-- Generated by python3 -m capital.build from data/. Do not edit. -->\n"


def blob_url(artifact: dict[str, Any] | None) -> str | None:
    if not artifact:
        return None
    ref = artifact.get("commit") or "main"
    return f"{REPO_URL}/blob/{ref}/{quote(artifact['path'])}"


def money(v: float | None) -> str:
    if v is None:
        return "—"
    return f"${v:,.2f}" if v < 1000 else f"${v:,.0f}"


def pct(v: float | None, signed: bool = True) -> str:
    if v is None:
        return "—"
    return f"{v:+.1%}" if signed else f"{v:.0%}"


def stance_label(call: dict[str, Any]) -> str:
    s = call.get("stance")
    if not s:
        return "unstated"
    label = s.replace("_", " ").capitalize()
    if call.get("bias") in ("positive", "negative"):
        label += f" ({call['bias']})"
    return label


def scen(call: dict[str, Any], case: str) -> dict[str, Any]:
    return (call.get("scenarios") or {}).get(case) or {}


