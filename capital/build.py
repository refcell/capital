def company_page(ticker: str, calls: list[store.Call]) -> str:
    calls = sorted(calls, key=lambda c: c.date)
    cur = calls[-1].call
    er = score.expected_annual(cur)
    rule = score.rule_rating(cur)
    m = score.mark(cur)
    out = [HEADER, f"# {cur['company']} ({cur.get('exchange') or ''}{': ' if cur.get('exchange') else ''}{ticker})\n"]
    out.append(f"Sector: {cur.get('sector') or '—'} · Calls: {len(calls)} · Latest: {cur['date']}\n")
    out.append("## Current view\n")
    rows = [
        ("Stance (as published)", cur["stance_text"]),
        ("Rule rating", f"{(rule or '—').capitalize()} ({pct(er)} a year expected over {config.RATING_HORIZON_YEARS} years)" if rule else "—"),
        ("Price at call", f"{money(cur['price']['value'])} on {cur['price'].get('date') or cur['date']}"),
        ("Bear / base / bull", " / ".join(money(scen(cur, c).get("value")) for c in ("bear", "base", "bull"))),
        ("Weights", " / ".join(pct(scen(cur, c).get("weight"), signed=False) for c in ("bear", "base", "bull"))),
        ("Fair value", f"{money(store.fair_value(cur))} ({(cur.get('fair_value') or {}).get('method', '—')})"),
        ("Street mean target", money((cur.get("street") or {}).get("target_mean"))),
        ("Valuation lens", cur.get("lens_text") or "—"),
    ]
    if m:
        rows.append(("Since the call", f"{pct(m.ret)} vs {config.RATING_BENCHMARK} {pct(m.bench_ret)} through {m.as_of}; mark {money(m.mark)} is {m.band or 'unbanded'}"))
    if cur.get("next_review"):
        rows.append(("Next review", f"{cur['next_review']} — {cur.get('next_review_trigger') or ''}".rstrip(" —")))
    out.append("| | |\n|---|---|")
    out.extend(f"| {k} | {str(v).replace('|', '/')} |" for k, v in rows)
    out.append("")
    if cur.get("thesis"):
        out.append(f"**Thesis.** {cur['thesis']}\n")
    if cur.get("variant_view"):
        out.append(f"**Variant view.** {cur['variant_view']}\n")
    if cur.get("catalysts"):
        out.append("**Catalysts.**\n")
        out.extend(f"- {k['event']}" + (f" ({k['timing']})" if k.get("timing") else "") for k in cur["catalysts"])
        out.append("")
    if cur.get("change_my_mind"):
        out.append("**What would change the view.**\n")
        out.extend(f"- {x}" for x in cur["change_my_mind"])
        out.append("")
    notes = [n for n in cur.get("notes", []) if "generated by" not in n]
    if notes:
        out.append("**Data notes.** " + " ".join(notes) + "\n")

    out.append("## Call history\n")
    out.append("| Date | Price | Stance | Rule | Bear | Base | Bull | Fair value | Since call | vs SPY | Mark band | Files |")
    out.append("|---|---:|---|---|---:|---:|---:|---:|---:|---:|---|---|")
    for c in reversed(calls):
        d = c.call
        mk = score.mark(d)
        links = []
        for name, label in (("report", "report"), ("projection", "projection"), ("model", "model"), ("build_script", "script")):
            url = blob_url((d.get("artifacts") or {}).get(name))
            if url:
                links.append(f"[{label}]({url})")
        out.append(
            f"| {d['date']} | {money(d['price']['value'])} | {stance_label(d)} | {(score.rule_rating(d) or '—').capitalize()} | "
            f"{money(scen(d, 'bear').get('value'))} | {money(scen(d, 'base').get('value'))} | {money(scen(d, 'bull').get('value'))} | "
            f"{money(store.fair_value(d))} | {pct(mk.ret) if mk else '—'} | {pct(mk.excess) if mk else '—'} | {mk.band if mk and mk.band else '—'} | "
            f"{' · '.join(links)} |"
        )
    out.append(f"\nData: `data/{ticker}/`. Prices: `data/prices/{ticker}.csv`.\n")
    return "\n".join(out)


