CSV_FIELDS = [
    "ticker", "date", "company", "sector", "origin", "research_status", "stance", "bias", "rule_rating",
    "primary_lens", "price", "price_date", "bear", "bear_weight", "base", "base_weight", "bull", "bull_weight",
    "fair_value", "fair_value_method", "expected_annual_return", "street_target_mean", "deviation_from_street_pct",
    "next_review", "report", "report_commit",
]


def calls_csv(calls: list[store.Call]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=CSV_FIELDS, lineterminator="\n")
    w.writeheader()
    for c in calls:
        d = c.call
        er = score.expected_annual(d)
        fv = d.get("fair_value") or {}
        rep = d["artifacts"]["report"]
        w.writerow({
            "ticker": d["ticker"], "date": d["date"], "company": d["company"], "sector": d.get("sector") or "",
            "origin": d["origin"], "research_status": d.get("research_status") or "", "stance": d.get("stance") or "",
            "bias": d.get("bias") or "", "rule_rating": score.rule_rating(d) or "", "primary_lens": d.get("primary_lens") or "",
            "price": d["price"]["value"], "price_date": d["price"].get("date") or "",
            "bear": scen(d, "bear").get("value", ""), "bear_weight": scen(d, "bear").get("weight", ""),
            "base": scen(d, "base").get("value", ""), "base_weight": scen(d, "base").get("weight", ""),
            "bull": scen(d, "bull").get("value", ""), "bull_weight": scen(d, "bull").get("weight", ""),
            "fair_value": fv.get("value", ""), "fair_value_method": fv.get("method", ""),
            "expected_annual_return": f"{er:.4f}" if er is not None else "",
            "street_target_mean": (d.get("street") or {}).get("target_mean", ""),
            "deviation_from_street_pct": (d.get("deviation_from_street") or {}).get("pct", ""),
            "next_review": d.get("next_review") or "", "report": rep["path"], "report_commit": rep.get("commit") or "",
        })
    return buf.getvalue()


